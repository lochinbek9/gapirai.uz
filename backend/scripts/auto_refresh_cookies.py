#!/usr/bin/env python3
"""
YouTube cookie'larni avtomatik yangilash
Google 2FA yo'q bo'lsa, oddiy parol ishlatiladi
"""
import asyncio
import os
import sys
from playwright.async_api import async_playwright

# Sozlamalar
YOUTUBE_EMAIL = os.getenv("YOUTUBE_EMAIL")
YOUTUBE_PASSWORD = os.getenv("YOUTUBE_PASSWORD")
COOKIES_PATH = os.getenv("YOUTUBE_COOKIES_PATH", "/app/cookies.txt")
HEADLESS = True

if not YOUTUBE_EMAIL or not YOUTUBE_PASSWORD:
    print("❌ Xato: YOUTUBE_EMAIL va YOUTUBE_PASSWORD .env faylida yo'q")
    sys.exit(1)

async def refresh_cookies():
    print(f"🔄 Cookie yangilanmoqda: {YOUTUBE_EMAIL}")
    
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=HEADLESS)
        context = await browser.new_context(
            user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
        )
        page = await context.new_page()
        
        try:
            # Google login
            await page.goto("https://accounts.google.com/signin")
            await page.wait_for_selector('input[type="email"]', timeout=15000)
            await page.fill('input[type="email"]', YOUTUBE_EMAIL)
            await page.click("#identifierNext")
            
            await page.wait_for_selector('input[type="password"]', timeout=15000)
            await page.fill('input[type="password"]', YOUTUBE_PASSWORD)
            await page.click("#passwordNext")
            
            # YouTube'ga o'tish
            await page.goto("https://www.youtube.com", wait_until="networkidle", timeout=30000)
            await page.wait_for_timeout(5000)
            
            # Cookie'larni olish
            cookies = await context.cookies()
            
            # Netscape formatda saqlash
            with open(COOKIES_PATH, "w") as f:
                f.write("# Netscape HTTP Cookie File\n")
                f.write("# https://curl.haxx.se/docs/http-cookies.html\n")
                f.write("# This file was generated by auto_refresh_cookies.py\n\n")
                
                for cookie in cookies:
                    domain = cookie.get("domain", "")
                    path = cookie.get("path", "/")
                    secure = "TRUE" if cookie.get("secure") else "FALSE"
                    expires = str(int(cookie.get("expires", 0)))
                    name = cookie.get("name", "")
                    value = cookie.get("value", "")
                    
                    if domain.startswith("."):
                        include_subdomains = "TRUE"
                    else:
                        include_subdomains = "FALSE"
                    
                    f.write(f"{domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}\n")
            
            print(f"✅ Cookie yangilandi: {COOKIES_PATH}")
            print(f"   Jami cookie soni: {len(cookies)}")
            
        except Exception as e:
            print(f"❌ Xato: {e}")
            sys.exit(1)
        finally:
            await browser.close()

if __name__ == "__main__":
    asyncio.run(refresh_cookies())
